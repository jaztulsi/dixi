// Builds data/blocklist.generated.txt (ad and tracker hosts Dixi's tabs never load; pages load faster)
// from the public StevenBlack unified hosts list. Never hand-written. Keeps the previous list on failure.
//   npm run refresh-blocklist
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SOURCE = 'https://raw.githubusercontent.com/StevenBlack/hosts/master/hosts';
const out = path.join(path.dirname(fileURLToPath(import.meta.url)), '../data/blocklist.generated.txt');

try {
  const res = await fetch(SOURCE, { signal: AbortSignal.timeout(30000) });
  if (!res.ok) throw new Error(`${SOURCE} → ${res.status}`);
  const hosts = new Set();
  for (const line of (await res.text()).split('\n')) {
    const m = line.match(/^0\.0\.0\.0\s+([a-z0-9.-]+\.[a-z]{2,})\s*(#.*)?$/i);
    if (m && m[1] !== '0.0.0.0') hosts.add(m[1].toLowerCase());
  }
  if (hosts.size < 10000) throw new Error(`only ${hosts.size} hosts`);
  fs.writeFileSync(out, `# Generated by scripts/refresh-blocklist.js from ${SOURCE} on ${new Date().toISOString().slice(0, 10)}; do not edit.\n${[...hosts].sort().join('\n')}\n`);
  console.log(`${hosts.size} hosts → data/blocklist.generated.txt`);
} catch (err) {
  console.error('Blocklist refresh failed, keeping the previous one:', err.message);
  process.exitCode = 1;
}
