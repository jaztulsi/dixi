// Builds data/unsafe.generated.txt (malware and phishing hosts Dixi never opens; src/main/safesite.js) from the
// public malware-filter host lists: URLhaus (abuse.ch) malware sites, and OpenPhish/PhishTank phishing sites.
// Both lists already leave out popular sites, so a shared host (drive.google.com) is never blocked whole.
// Never hand-written. Keeps the previous list on failure.   npm run refresh-unsafe
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SOURCES = [
  'https://malware-filter.gitlab.io/malware-filter/urlhaus-filter-hosts.txt',
  'https://malware-filter.gitlab.io/malware-filter/phishing-filter-hosts.txt',
];
const out = path.join(path.dirname(fileURLToPath(import.meta.url)), '../data/unsafe.generated.txt');

try {
  const hosts = new Set();
  for (const src of SOURCES) {
    const res = await fetch(src, { signal: AbortSignal.timeout(30000) });
    if (!res.ok) throw new Error(`${src} → ${res.status}`);
    const before = hosts.size;
    for (const line of (await res.text()).split('\n')) {
      const m = line.match(/^0\.0\.0\.0\s+([a-z0-9.-]+\.[a-z0-9-]{2,})\s*(#.*)?$/i);
      if (m) hosts.add(m[1].toLowerCase());
    }
    if (hosts.size - before < 500) throw new Error(`only ${hosts.size - before} hosts from ${src}`);
  }
  fs.writeFileSync(out, `# Generated by scripts/refresh-unsafe.js from ${SOURCES.join(' and ')} on ${new Date().toISOString().slice(0, 10)}; do not edit.\n${[...hosts].sort().join('\n')}\n`);
  console.log(`${hosts.size} hosts → data/unsafe.generated.txt`);
} catch (err) {
  console.error('Unsafe-site list refresh failed, keeping the previous one:', err.message);
  process.exitCode = 1;
}
