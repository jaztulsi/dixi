// The only bridge between the UI and the main process. No keys cross it, only results.
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('dixi', {
  config: () => ipcRenderer.invoke('config:get'),
  llm: (req) => ipcRenderer.invoke('llm:chat', req),
  llmAbort: (id) => ipcRenderer.send('llm:abort', id),
  spend: () => ipcRenderer.invoke('spend:get'),
  resolve: (q) => ipcRenderer.invoke('resolve:site', q),
  registry: {
    names: () => ipcRenderer.invoke('registry:names'),
    all: () => ipcRenderer.invoke('registry:all'),
    lookup: (name) => ipcRenderer.invoke('registry:lookup', name),
    outcome: (host, ok) => ipcRenderer.invoke('registry:outcome', host, ok),
    confirm: (said, hit) => ipcRenderer.invoke('registry:confirm', said, hit),
    template: (host, tpl) => ipcRenderer.invoke('registry:template', host, tpl),
    clear: () => ipcRenderer.invoke('registry:clear'),
  },
  tabExec: (id, code, timeoutMs) => ipcRenderer.invoke('tab:exec', id, code, timeoutMs),
  openSearchTemplate: (url) => ipcRenderer.invoke('tab:opensearch', url),
  discoverSearch: (url) => ipcRenderer.invoke('tab:discover-search', url),
  tts: (text) => ipcRenderer.invoke('tts:speak', text),
  webAnswer: (question) => ipcRenderer.invoke('answer:web', question),
  preconnect: (url) => ipcRenderer.send('net:preconnect', url),
  catalog: () => ipcRenderer.invoke('catalog:get'),
  trace: (line) => ipcRenderer.send('trace:write', line),
  traceShot: (webContentsId, name) => ipcRenderer.invoke('trace:shot', webContentsId, name),
  deepgram: {
    open: (params) => ipcRenderer.invoke('deepgram:open', params),
    sendAudio: (chunk) => ipcRenderer.send('deepgram:audio', chunk),
    control: (message) => ipcRenderer.send('deepgram:control', message),
    close: () => ipcRenderer.invoke('deepgram:close'),
    onMessage: (fn) => ipcRenderer.on('deepgram:message', (_e, text) => fn(text)),
    onClosed: (fn) => ipcRenderer.on('deepgram:closed', (_e, code) => fn(code)),
  },
  screenshot: (webContentsId) => ipcRenderer.invoke('tab:screenshot', webContentsId),
  openExternal: (url) => ipcRenderer.invoke('shell:open-external', url),
  onOpenURL: (fn) => ipcRenderer.on('app:open-url', (_e, url) => fn(url)),
  onPopup: (fn) => ipcRenderer.on('tab:popup', (_e, url) => fn(url)),
  // Dixi Everywhere: the whole Mac (main/everywhere.js). enabled() rejects when it's off.
  everywhere: {
    enabled: () => ipcRenderer.invoke('everywhere:enabled'),
    run: (text, mode) => ipcRenderer.invoke('everywhere:run', text, mode),
    speaking: (on) => ipcRenderer.send('everywhere:speaking', on),
    transcript: (text) => ipcRenderer.send('everywhere:transcript', text),
    stop: () => ipcRenderer.send('everywhere:stop'),
    confirmReply: (id, ok) => ipcRenderer.send('everywhere:confirm-reply', id, ok),
    onListen: (fn) => ipcRenderer.on('everywhere:listen', () => fn()),
    onDisarm: (fn) => ipcRenderer.on('everywhere:disarm', () => fn()),
    onFinish: (fn) => ipcRenderer.on('everywhere:finish', () => fn()),
    sessionEnded: () => ipcRenderer.send('everywhere:session-end'),
    onSay: (fn) => ipcRenderer.on('everywhere:say', (_e, text) => fn(text)),
    onConfirm: (fn) => ipcRenderer.on('everywhere:confirm', (_e, c) => fn(c)),
    onConfirmDone: (fn) => ipcRenderer.on('everywhere:confirm-done', (_e, id) => fn(id)),
    onMic: (fn) => ipcRenderer.on('everywhere:mic', (_e, on) => fn(on)),
    onKill: (fn) => ipcRenderer.on('everywhere:kill', () => fn()),
    onAsk: (fn) => ipcRenderer.on('everywhere:ask', (_e, q) => fn(q)),
    onCommands: (fn) => ipcRenderer.on('everywhere:commands', (_e, list) => fn(list)),
    onBrowse: (fn) => ipcRenderer.on('everywhere:browse', (_e, d) => fn(String(d?.text ?? ''), String(d?.id ?? ''))),   // a planned web step's words (and its id), nothing else
    browsed: (id, ok, error) => ipcRenderer.send('everywhere:browsed', String(id), Boolean(ok), String(error ?? '').slice(0, 200)),
    answer: (id, text) => ipcRenderer.send('everywhere:answer', id, text),
  },
});
