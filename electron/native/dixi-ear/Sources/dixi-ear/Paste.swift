import AppKit
import ApplicationServices

/// Dictation: put the words in the focused field with ⌘V, then put your clipboard back.
/// The clipboard copy is marked transient/concealed so clipboard managers don't keep it.
enum Paste {
  private static let marks = ["org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType", "de.petermaurer.TransientPasteboardType"].map { NSPasteboard.PasteboardType($0) }

  static func text(_ text: String, restoreAfter: TimeInterval = 1.0) {
    guard AXIsProcessTrusted() else { Out.error("paste", "Dixi needs Accessibility permission to paste."); Out.emit(["ev": "pasted", "ok": false]); return }
    let pb = NSPasteboard.general
    // Everything that was on the clipboard, every type of every item.
    let saved: [NSPasteboardItem] = (pb.pasteboardItems ?? []).map { item in
      let copy = NSPasteboardItem()
      for type in item.types { if let d = item.data(forType: type) { copy.setData(d, forType: type) } }
      return copy
    }
    pb.declareTypes([.string] + marks, owner: nil)
    pb.setString(text, forType: .string)
    for m in marks { pb.setString("", forType: m) }
    let ours = pb.changeCount
    let src = CGEventSource(stateID: .hidSystemState)
    let down = CGEvent(keyboardEventSource: src, virtualKey: 9, keyDown: true)   // 9 = V
    let up = CGEvent(keyboardEventSource: src, virtualKey: 9, keyDown: false)
    down?.flags = .maskCommand; up?.flags = .maskCommand
    down?.post(tap: .cgSessionEventTap); up?.post(tap: .cgSessionEventTap)
    Out.emit(["ev": "pasted", "ok": true])
    // Some apps read ⌘V a little later; and if you copied something new meanwhile, that stays.
    DispatchQueue.main.asyncAfter(deadline: .now() + restoreAfter) {
      guard pb.changeCount == ours else { return }
      pb.clearContents()
      if !saved.isEmpty { pb.writeObjects(saved) }
    }
  }
}
